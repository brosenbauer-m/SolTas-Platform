-- Migration: iati_activities
-- Created: 2026-10-13
--
-- WHAT:
--   Tables for activities imported from the IATI Datastore (docs/architecture/iati-integration.md).
--   - iati_activities: one row per IATI activity. Public, read-only copy of open data.
--     Written only by the nightly sync (service role, bypasses RLS).
--   - iati_sync_runs: log of sync runs and the incremental high-water mark. Server only.
--
-- ACCESS:
--   - anon + authenticated: SELECT rows that are not hidden and not withdrawn.
--   - admins: SELECT every row, UPDATE only the "hidden" column (moderation).
--   - nobody but the service role inserts or deletes.
--   - iati_sync_runs: RLS on, no policies, no grants (service role only).
--
-- SIZE: rows are kept compact (description capped by the sync) because the project is on
--   Supabase Free (500 MB). The sync caps the number of activities too.

begin;

create table if not exists public.iati_activities (
  iati_identifier     text primary key,
  title               text not null,
  description         text,
  reporting_org_ref   text,
  reporting_org_name  text,
  reporting_org_type  text,
  -- [{role, ref, name, type}]
  participating_orgs  jsonb not null default '[]'::jsonb,
  -- IATI ActivityStatus 1-6 and our lifecycle slug (same words as projects.lifecycle_status)
  activity_status     smallint,
  lifecycle_status    text not null default 'planned'
                      check (lifecycle_status in ('planned', 'ongoing', 'completed', 'cancelled', 'paused')),
  start_date          date,
  end_date            date,
  countries           text[] not null default '{}',   -- ISO 3166-1 alpha-2
  regions             text[] not null default '{}',   -- IATI region codes
  scope               text,                           -- IATI ActivityScope code
  -- [{name, lat, lng, exactness}]
  locations           jsonb not null default '[]'::jsonb,
  -- the point drawn on the map; country/region = centroid, drawn as "approximate"
  lat                 double precision check (lat between -90 and 90),
  lng                 double precision check (lng between -180 and 180),
  point_precision     text check (point_precision in ('exact', 'country', 'region')),
  dac_sectors         text[] not null default '{}',   -- DAC 5-digit (or 3-digit) codes
  sectors             text[] not null default '{}',   -- our shared Sector slugs (filled once taxonomies exist)
  -- [{code, significance}]
  policy_markers      jsonb not null default '[]'::jsonb,
  humanitarian        boolean not null default false,
  sdgs                text[] not null default '{}',
  budget_total        numeric,
  currency            text,
  -- [{url, title}]
  links               jsonb not null default '[]'::jsonb,
  last_updated_at     timestamptz,                    -- IATI last-updated-datetime
  synced_at           timestamptz not null default now(),
  withdrawn_at        timestamptz,                    -- left the scope or IATI; hidden, not deleted
  hidden              boolean not null default false  -- set by admins
);

create index if not exists iati_activities_map_idx
  on public.iati_activities (lat, lng)
  where not hidden and withdrawn_at is null and lat is not null;
create index if not exists iati_activities_last_updated_idx on public.iati_activities (last_updated_at);
create index if not exists iati_activities_reporting_org_idx on public.iati_activities (reporting_org_ref);
create index if not exists iati_activities_countries_idx on public.iati_activities using gin (countries);
create index if not exists iati_activities_dac_sectors_idx on public.iati_activities using gin (dac_sectors);
create index if not exists iati_activities_sectors_idx on public.iati_activities using gin (sectors);

alter table public.iati_activities enable row level security;

revoke all on public.iati_activities from anon, authenticated;
grant select on public.iati_activities to anon, authenticated;
grant update (hidden) on public.iati_activities to authenticated;
grant all on public.iati_activities to service_role;

drop policy if exists iati_activities_public_read on public.iati_activities;
create policy iati_activities_public_read on public.iati_activities
  for select to anon, authenticated
  using (not hidden and withdrawn_at is null);

drop policy if exists iati_activities_admin_read on public.iati_activities;
create policy iati_activities_admin_read on public.iati_activities
  for select to authenticated
  using (public.is_admin());

drop policy if exists iati_activities_admin_hide on public.iati_activities;
create policy iati_activities_admin_hide on public.iati_activities
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create table if not exists public.iati_sync_runs (
  id               bigint generated by default as identity primary key,
  mode             text not null check (mode in ('count', 'dry-run', 'incremental', 'full')),
  started_at       timestamptz not null default now(),
  finished_at      timestamptz,
  ok               boolean,
  -- next incremental run asks IATI for activities updated since this time
  high_water_mark  timestamptz,
  in_scope         integer,
  fetched          integer not null default 0,
  upserted         integer not null default 0,
  withdrawn        integer not null default 0,
  error            text
);

alter table public.iati_sync_runs enable row level security;
revoke all on public.iati_sync_runs from anon, authenticated;
grant all on public.iati_sync_runs to service_role;

commit;
