-- One row per AI (Mistral) request: who, which feature, tokens. Used for the daily limit per person
-- (AI project search) and to keep AI costs in check (target: at most half of a membership fee).
-- Server only: RLS on, no policies, no grants for anon/authenticated; API routes write it with the
-- service role. Rows hold no prompt or answer text.

begin;

create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  feature text not null check (feature in ('search', 'tagging')),
  model text not null,
  input_tokens integer not null default 0 check (input_tokens >= 0),
  output_tokens integer not null default 0 check (output_tokens >= 0),
  created_at timestamptz not null default now()
);

create index if not exists ai_usage_user_feature_day_idx on public.ai_usage (user_id, feature, created_at);

alter table public.ai_usage enable row level security;
revoke all on public.ai_usage from anon, authenticated;
grant all on public.ai_usage to service_role;
grant usage, select on sequence public.ai_usage_id_seq to service_role;

commit;
